#!/usr/bin/env python3
"""Generate model weight names/shapes, never checkpoint data or offsets."""

import json
from pathlib import Path

try:
    from .format_assembly import format_source
except ImportError:
    from format_assembly import format_source

ROOT = Path(__file__).resolve().parents[1]


def schema(config=None):
    config = config or json.loads((ROOT / "docs/config.json").read_text())
    hidden = config["hidden_size"]
    dim = config["head_dim"]
    intermediate = config["intermediate_size"]
    vocab = config["vocab_size"]
    query_width = config["num_attention_heads"] * dim
    kv_width = config["num_key_value_heads"] * dim
    rows = [("model.embed_tokens.weight", [vocab, hidden]), ("model.norm.weight", [hidden])]
    if not config["tie_word_embeddings"]:
        rows.append(("lm_head.weight", [vocab, hidden]))
    # Order is part of the generated assembly ABI: slots are addressed by index.
    shapes = {
        "mixer.qkv_proj.weight": [query_width + 2 * kv_width, hidden],
        "mixer.o_proj.weight": [hidden, query_width],
        "mixer.q_norm.weight": [dim],
        "mixer.k_norm.weight": [dim],
        "mlp.gate_up_proj.weight": [2 * intermediate, hidden],
        "mlp.down_proj.weight": [hidden, intermediate],
        "pre_mixer_norm.weight": [hidden],
        "post_mixer_norm.weight": [hidden],
        "pre_mlp_norm.weight": [hidden],
        "post_mlp_norm.weight": [hidden],
    }
    for layer in range(config["num_hidden_layers"]):
        prefix = f"model.layers.layers.{layer}."
        rows.extend((prefix + name, list(shape)) for name, shape in shapes.items())
    return rows


def render(config=None):
    rows = schema(config)
    lines = [
        "// Generated by tools/weight_schema.py; original BF16 tensors remain unchanged.",
        ".data",
        ".p2align 3",
        ".globl _plamo_weight_schema",
        "_plamo_weight_schema:",
    ]
    for index, (_, shape) in enumerate(rows):
        lines.append(
            f".quad Lweightname{index},{len(shape)},Lweightdims{index},_plamo_weights+{index * 8}"
        )
    lines += [".quad 0,0,0,0", ".section __TEXT,__const"]
    for index, (name, shape) in enumerate(rows):
        lines += [
            f'Lweightname{index}: .asciz "{name}"',
            ".p2align 3",
            f"Lweightdims{index}: .quad " + ",".join(map(str, shape)),
        ]
    lines += [".globl _plamo_weights", f".zerofill __DATA,__bss,_plamo_weights,{len(rows) * 8},3"]
    return format_source("\n".join(lines))


def main():
    (ROOT / "src/weight_schema.s").write_text(render())


if __name__ == "__main__":
    main()
