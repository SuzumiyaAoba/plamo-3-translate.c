#!/usr/bin/env python3
"""Emit fixed model RoPE constants without reading checkpoint weights."""

import json
import math
from pathlib import Path
import struct

try:
    from .format_assembly import format_source
except ImportError:
    from format_assembly import format_source

ROOT = Path(__file__).resolve().parents[1]


def fp(value):
    return struct.unpack("f", struct.pack("f", value))[0]


def frequencies(parameters, half):
    base = parameters["rope_theta"]
    yarn = parameters["rope_type"] == "yarn"
    if yarn:
        low = (
            half
            * math.log(
                parameters["original_max_position_embeddings"]
                / (parameters["beta_fast"] * 2 * math.pi)
            )
            / math.log(base)
        )
        high = (
            half
            * math.log(
                parameters["original_max_position_embeddings"]
                / (parameters["beta_slow"] * 2 * math.pi)
            )
            / math.log(base)
        )
    values = []
    for index in range(half):
        frequency = fp(base ** (index / half))
        extrapolated = fp(1 / frequency)
        if yarn:
            # Each intermediate follows upstream FP32 tensor operations.
            ramp = fp(fp(index - fp(low)) / fp(high - low))
            mask = fp(1 - max(0, min(1, ramp)))
            interpolated = fp(1 / fp(parameters["factor"] * frequency))
            extrapolated = fp(fp(interpolated * fp(1 - mask)) + fp(extrapolated * mask))
        values.append(extrapolated)
    return values


def render(config=None):
    config = config or json.loads((ROOT / "docs/config.json").read_text())
    half = config["head_dim"] // 2
    lines = [
        "// Generated by tools/rope_constants.py from docs/config.json.",
        ".section __TEXT,__const",
        ".p2align 2",
    ]
    for name, key in (("local", "sliding_attention"), ("global", "full_attention")):
        parameters = config["rope_parameters"][key]
        values = frequencies(parameters, half)
        symbol = "_plamo_rope_" + name
        lines += [".globl " + symbol, symbol + ":", ".float " + ",".join(map(repr, values))]
        concentration = (
            1 if parameters["rope_type"] == "default" else 1 + 0.1 * math.log(parameters["factor"])
        )
        lines += [
            ".globl " + symbol + "_scale",
            symbol + "_scale:",
            ".float " + repr(fp(concentration)),
        ]
    return format_source("\n".join(lines))


def main():
    (ROOT / "src/rope_constants.s").write_text(render())


if __name__ == "__main__":
    main()
