#!/usr/bin/env python3
"""Generate fixed model descriptors and shared scratch; no weight conversion."""

import json
import math
from pathlib import Path

try:
    from .format_assembly import format_source
    from .weight_schema import schema
except ImportError:
    from format_assembly import format_source
    from weight_schema import schema

ROOT = Path(__file__).resolve().parents[1]


class Layout:
    """Resolve weight slots and arena addresses while emitting ABI records.

    Callers describe each record once. All pointer patching, buffer alignment
    and assembly serialization stay here, below the model's layer structure.
    """

    def __init__(self, config):
        self.slots = {name: index for index, (name, _) in enumerate(schema(config))}
        if config["tie_word_embeddings"]:
            self.slots["lm_head.weight"] = self.slots["model.embed_tokens.weight"]
        self.lines = ["// Generated by tools/model_layout.py.", ".data", ".p2align 3"]
        self.buffers = {}
        self.weight_patches = []
        self.arena_patches = []

    def buffer(self, name, count):
        self.buffers[name] = count * 4

    def record(self, name, items):
        values = []
        for index, item in enumerate(items):
            if isinstance(item, str) and item in self.buffers:
                self.arena_patches.append((name, index * 8, item))
                values.append(0)
            else:
                values.append(item)
        self.lines.append(name + ": .quad " + ",".join(map(str, values)))

    def weight(self, record, offset, name):
        self.weight_patches.append((record, offset, self.slots[name]))

    def render(self):
        lines = self.lines + [".globl _plamo_model_patches", "_plamo_model_patches:"]
        for record, offset, slot in self.weight_patches:
            lines.append(f".quad {record}+{offset},_plamo_weights+{slot * 8}")
        lines.append(".quad 0,0")
        offsets, total = {}, 0
        for name, size in self.buffers.items():
            total = (total + 15) // 16 * 16
            offsets[name] = total
            total += size
        lines += [
            ".globl _plamo_arena_size",
            "_plamo_arena_size: .quad " + str(total),
            ".globl _plamo_arena_patches",
            "_plamo_arena_patches:",
        ]
        for record, offset, name in self.arena_patches:
            lines.append(f".quad {record}+{offset},{offsets[name]}")
        return format_source("\n".join(lines + [".quad 0,0"]))


def add_layer(layout, config, index):
    hidden, dim = config["hidden_size"], config["head_dim"]
    query_heads, kv_heads = config["num_attention_heads"], config["num_key_value_heads"]
    intermediate = config["intermediate_size"]
    full = (index + 1) % config["sliding_window_pattern"] == 0
    capacity = config["max_position_embeddings"] if full else config["window_size"] + 1
    frequency = "_plamo_rope_global" if full else "_plamo_rope_local"
    prefix = f"model.layers.layers.{index}."
    qkv, cache, rotation, gqa = (f"L{name}{index}" for name in ("q", "c", "r", "g"))
    mixer, mlp, layer = (f"L{name}{index}" for name in ("m", "p", "l"))
    for name in ("keys", "values", "rotated"):
        layout.buffer(f"L{name}{index}", capacity * kv_heads * dim)
    layout.record(
        qkv, ["Lwork_normalized", 0, 0, 0, "Lwork_qkvout", hidden, query_heads, kv_heads, dim]
    )
    for offset, name in (
        (8, "mixer.qkv_proj.weight"),
        (16, "mixer.q_norm.weight"),
        (24, "mixer.k_norm.weight"),
    ):
        layout.weight(qkv, offset, prefix + name)
    layout.record(
        cache, [f"Lkeys{index}", f"Lvalues{index}", capacity, 0, kv_heads * dim, int(not full)]
    )
    layout.record(
        rotation,
        [cache, f"Lrotated{index}", frequency, "Lwork_cos", "Lwork_sin", kv_heads, dim, 0, 0],
    )
    layout.record(
        gqa,
        [
            "Lwork_qkvout",
            f"Lrotated{index}",
            f"Lvalues{index}",
            "Lwork_attention",
            "Lwork_scores",
            0,
            dim,
            query_heads,
            kv_heads,
        ],
    )
    layout.record(mixer, [qkv, cache, rotation, gqa, 0, "Lwork_branch", hidden])
    layout.weight(mixer, 32, prefix + "mixer.o_proj.weight")
    layout.record(
        mlp,
        [
            "Lwork_state",
            0,
            0,
            0,
            0,
            "Lwork_normalized",
            "Lwork_branch",
            "Lwork_mlpscratch",
            hidden,
            intermediate,
        ],
    )
    for offset, name in (
        (8, "pre_mlp_norm.weight"),
        (16, "post_mlp_norm.weight"),
        (24, "mlp.gate_up_proj.weight"),
        (32, "mlp.down_proj.weight"),
    ):
        layout.weight(mlp, offset, prefix + name)
    layout.record(
        layer, ["Lwork_state", 0, 0, "Lwork_normalized", "Lwork_branch", mixer, mlp, hidden]
    )
    for offset, name in ((8, "pre_mixer_norm.weight"), (16, "post_mixer_norm.weight")):
        layout.weight(layer, offset, prefix + name)


def render(config=None):
    config = config or json.loads((ROOT / "docs/config.json").read_text())
    hidden, dim = config["hidden_size"], config["head_dim"]
    query_heads, kv_heads = config["num_attention_heads"], config["num_key_value_heads"]
    intermediate, count = config["intermediate_size"], config["num_hidden_layers"]
    vocab, context = config["vocab_size"], config["max_position_embeddings"]
    layout = Layout(config)
    for name, size in (
        ("state", hidden),
        ("normalized", hidden),
        ("branch", hidden),
        ("qkvout", (query_heads + 2 * kv_heads) * dim),
        ("attention", query_heads * dim),
        ("mlpscratch", 2 * intermediate),
        ("scores", context),
        ("cos", dim // 2),
        ("sin", dim // 2),
        ("logits", vocab),
    ):
        layout.buffer("Lwork_" + name, size)
    for index in range(count):
        add_layer(layout, config, index)
    layout.record("Llayers", [f"Ll{index}" for index in range(count)])
    factor = config["rope_parameters"]["full_attention"]["factor"]
    scales = [
        1 + 0.1 * math.log(factor) if (index + 1) % config["sliding_window_pattern"] == 0 else 1.0
        for index in range(count)
    ]
    layout.lines += [
        "Lscales: .float " + ",".join(map(str, scales)),
        ".p2align 3",
        ".globl _plamo_model",
    ]
    layout.record(
        "_plamo_model",
        [
            0,
            vocab,
            hidden,
            "Lwork_state",
            "Llayers",
            count,
            "Lscales",
            0,
            "Lwork_normalized",
            0,
            "Lwork_logits",
        ],
    )
    for offset, name in (
        (0, "model.embed_tokens.weight"),
        (56, "model.norm.weight"),
        (72, "lm_head.weight"),
    ):
        layout.weight("_plamo_model", offset, name)
    return layout.render()


def main():
    (ROOT / "src/model_layout.s").write_text(render())


if __name__ == "__main__":
    main()
