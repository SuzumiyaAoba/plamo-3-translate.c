#!/usr/bin/env python3
"""Generate static descriptors and paths, without opening model weights."""

import argparse
import json
from pathlib import Path

try:
    from . import model_layout, rope_constants, weight_schema
    from .format_assembly import format_source
    from .model_catalog import add_model_argument, profile
except ImportError:
    import model_layout, rope_constants, weight_schema
    from format_assembly import format_source
    from model_catalog import add_model_argument, profile


def render_profile(p):
    if not 1 <= len(p.weights) <= 64:
        raise ValueError("a model must have 1..64 weight files")
    lines = [
        "// Generated by tools/generate_model.py; no checkpoint data.",
        ".data",
        ".p2align 3",
        ".globl _plamo_weight_file_count",
        f"_plamo_weight_file_count: .quad {len(p.weights)}",
        ".globl _plamo_weight_paths",
        "_plamo_weight_paths: .quad " + ",".join(f"Lpath{i}" for i in range(len(p.weights))),
        ".section __TEXT,__const",
    ]
    strings = [(f"Lpath{i}", str(p.directory / name)) for i, name in enumerate(p.weights)]
    for name, value in (
        ("plamo_vocab_path", str(p.directory / "tokenizer.jsonl")),
        ("plamo_model_name", p.name),
        ("plamo_model_repository", p.repository),
        ("plamo_model_revision", p.revision),
    ):
        lines.append(".globl _" + name)
        strings.append(("_" + name, value))
    lines += [f"{name}: .asciz {json.dumps(value)}" for name, value in strings]
    return format_source("\n".join(lines))


def generate(p, directory):
    c = p.config
    # The tokenizer and kernels deliberately implement this family, not arbitrary HF models.
    if (
        c["model_type"] != "plamo3"
        or c["dtype"] != "bfloat16"
        or c["scale_embedding"]
        or c["vocab_size"] != 107520
        or c["rms_norm_eps"] != 1e-6
    ):
        raise ValueError("unsupported model architecture")
    directory.mkdir(parents=True, exist_ok=True)
    outputs = {
        "weight_schema.s": weight_schema.render(c),
        "model_layout.s": model_layout.render(c),
        "rope_constants.s": rope_constants.render(c),
        "model_profile.s": render_profile(p),
    }
    for name, text in outputs.items():
        (directory / name).write_text(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    add_model_argument(parser)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    generate(profile(args.model), args.output)


if __name__ == "__main__":
    main()
